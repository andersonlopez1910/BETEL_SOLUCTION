-- Rol sin privilegios de superusuario para el runtime de Betel.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'betel_app') THEN
    CREATE ROLE betel_app LOGIN PASSWORD 'betel_app_local' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  END IF;
END $$;

GRANT CONNECT ON DATABASE betel TO betel_app;
GRANT USAGE ON SCHEMA public TO betel_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO betel_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO betel_app;
ALTER DEFAULT PRIVILEGES FOR USER betel IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO betel_app;
ALTER DEFAULT PRIVILEGES FOR USER betel IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO betel_app;
